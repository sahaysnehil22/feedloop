const dicts: Record<Lang, Strings> = { en, es };

export function getStrings(lang: Lang): Strings {
  return dicts[lang] ?? en;
}

export function t(lang: Lang, key: keyof Strings): string {
  const d = getStrings(lang);
  return d[key] ?? en[key] ?? key;
}

export function statusLabel(lang: Lang, s: Status): string {
  return t(lang, `status.${s}` as keyof Strings);
}

export function normalizeLang(v: string | null | undefined): Lang {
  return v === "es" ? "es" : "en";
}
